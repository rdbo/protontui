//! DNS backends: systemd-resolved, `resolvconf`, or rewriting `/etc/resolv.conf` (T3.4).
//!
//! [`Backend::detect`] picks one: systemd-resolved when it owns `org.freedesktop.resolve1` on the system bus
//! and `/etc/resolv.conf` points at it; else openresolv when it generated `/etc/resolv.conf`; else the file
//! backend. A backend that only *exists* isn't enough: if resolv.conf doesn't come from it, its changes
//! wouldn't reach the resolver, and undoing them wouldn't give back the original file.
//!
//! Contract for the file backend, which [`recover`] relies on:
//! - Before writing, the original is backed up into [`crate::config::RUN_DIR`]: its bytes to [`BACKUP_FILE`]
//!   when it's a regular file, or its link target to [`SYMLINK_BACKUP_FILE`] when it's a symlink (the link is
//!   then replaced by a regular file, never written through).
//! - The written file starts with [`MARKER`].
//! - Restore happens only while the file still carries the marker; otherwise someone else (DHCP, the admin)
//!   has rewritten it since, and the backup is stale.

use std::io::{self, Write};
use std::net::IpAddr;
use std::path::{Path, PathBuf};
use std::process::Stdio;

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use tokio::io::AsyncWriteExt;
use tokio::process::Command;

use crate::config;
use crate::vpn::wireguard::INTERFACE;

pub const RESOLV_CONF: &str = "/etc/resolv.conf";
/// First line of every resolv.conf protontui writes.
pub const MARKER: &str = "# Generated by protontui";
pub const BACKUP_FILE: &str = "resolv.conf.bak";
pub const SYMLINK_BACKUP_FILE: &str = "resolv.conf.bak.symlink";
/// Environment override for the backend (`resolved`, `resolvconf` or `file`).
pub const BACKEND_ENV: &str = "PROTONTUI_DNS_BACKEND";

const RESOLVED_BUS_NAME: &str = "org.freedesktop.resolve1";
const RESOLVCONF_HEADER: &str = "# Generated by resolvconf";
/// errno for "Device or resource busy": `rename` over a bind-mounted file (containers, `ip netns exec`).
const EBUSY: i32 = 16;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Backend {
    /// systemd-resolved, per-link settings over D-Bus.
    Resolved,
    /// openresolv: an exclusive entry for the tunnel interface.
    Resolvconf,
    /// Rewrite `/etc/resolv.conf`, with a backup.
    File,
}

impl Backend {
    pub async fn detect() -> Self {
        match std::env::var(BACKEND_ENV).ok().as_deref() {
            Some("resolved") => return Self::Resolved,
            Some("resolvconf") => return Self::Resolvconf,
            Some("file") => return Self::File,
            _ => {}
        }
        let resolv_conf = Path::new(RESOLV_CONF);
        if uses_resolved_stub(resolv_conf) && resolved_running().await {
            return Self::Resolved;
        }
        let generated_by_resolvconf = std::fs::read_to_string(resolv_conf)
            .is_ok_and(|text| text.lines().next().is_some_and(|l| l.starts_with(RESOLVCONF_HEADER)));
        if generated_by_resolvconf && which("resolvconf") {
            return Self::Resolvconf;
        }
        Self::File
    }

    /// Points the system resolver at `servers`, through the tunnel link `ifindex`.
    pub async fn apply(self, ifindex: u32, servers: &[IpAddr]) -> Result<()> {
        anyhow::ensure!(!servers.is_empty(), "no DNS servers to set");
        match self {
            Self::Resolved => resolved_apply(ifindex, servers).await,
            Self::Resolvconf => resolvconf_apply(servers).await,
            Self::File => apply_file(Path::new(RESOLV_CONF), Path::new(config::RUN_DIR), servers),
        }
        .with_context(|| format!("setting DNS ({self:?} backend)"))
    }

    /// Undoes [`Backend::apply`]. Safe to call when nothing was applied.
    pub async fn revert(self, ifindex: u32) -> Result<()> {
        match self {
            Self::Resolved => resolved_revert(ifindex).await,
            Self::Resolvconf => recover_resolvconf().await.map(drop),
            Self::File => restore_file(Path::new(RESOLV_CONF), Path::new(config::RUN_DIR)).map(drop),
        }
        .with_context(|| format!("restoring DNS ({self:?} backend)"))
    }
}

/// The resolv.conf body protontui writes (file backend) or hands to openresolv.
pub fn resolv_conf_contents(servers: &[IpAddr], with_marker: bool) -> String {
    let mut text = String::new();
    if with_marker {
        text.push_str(MARKER);
        text.push_str("\n# Proton VPN DNS. The original file comes back on disconnect, or with `protontui recover`.\n");
    }
    for server in servers {
        text.push_str(&format!("nameserver {server}\n"));
    }
    text
}

fn uses_resolved_stub(resolv_conf: &Path) -> bool {
    if let Ok(target) = std::fs::read_link(resolv_conf)
        && target.to_string_lossy().contains("systemd/resolve")
    {
        return true;
    }
    std::fs::read_to_string(resolv_conf).is_ok_and(|t| t.lines().any(|l| l.trim() == "nameserver 127.0.0.53"))
}

async fn resolved_running() -> bool {
    let Ok(connection) = zbus::Connection::system().await else {
        return false;
    };
    let Ok(dbus) = zbus::fdo::DBusProxy::new(&connection).await else {
        return false;
    };
    match RESOLVED_BUS_NAME.try_into() {
        Ok(name) => dbus.name_has_owner(name).await.unwrap_or(false),
        Err(_) => false,
    }
}

async fn resolved_manager(connection: &zbus::Connection) -> Result<zbus::Proxy<'static>> {
    Ok(zbus::Proxy::new(connection, RESOLVED_BUS_NAME, "/org/freedesktop/resolve1", "org.freedesktop.resolve1.Manager")
        .await?)
}

async fn resolved_apply(ifindex: u32, servers: &[IpAddr]) -> Result<()> {
    let connection = zbus::Connection::system().await?;
    let manager = resolved_manager(&connection).await?;
    let link = ifindex as i32;
    let addresses: Vec<(i32, Vec<u8>)> = servers
        .iter()
        .map(|ip| match ip {
            IpAddr::V4(v4) => (libc_af_inet(), v4.octets().to_vec()),
            IpAddr::V6(v6) => (libc_af_inet6(), v6.octets().to_vec()),
        })
        .collect();
    manager.call::<_, _, ()>("SetLinkDNS", &(link, addresses)).await?;
    // `~.`: route every domain to this link, so other links' DNS servers aren't asked (no leak).
    manager.call::<_, _, ()>("SetLinkDomains", &(link, vec![("~.", true)])).await?;
    // Older systemd (< 240) lacks this; `~.` alone does the job there.
    if let Err(e) = manager.call::<_, _, ()>("SetLinkDefaultRoute", &(link, true)).await {
        tracing::debug!("SetLinkDefaultRoute: {e}");
    }
    Ok(())
}

async fn resolved_revert(ifindex: u32) -> Result<()> {
    let connection = zbus::Connection::system().await?;
    let manager = resolved_manager(&connection).await?;
    match manager.call::<_, _, ()>("RevertLink", &(ifindex as i32,)).await {
        Ok(()) => Ok(()),
        // The link is already gone, and its settings with it.
        Err(e) if e.to_string().contains("Link") => Ok(()),
        Err(e) => Err(e.into()),
    }
}

fn libc_af_inet() -> i32 {
    2
}

fn libc_af_inet6() -> i32 {
    10
}

async fn resolvconf_apply(servers: &[IpAddr]) -> Result<()> {
    // `-m 0`: lowest metric, first in the list; `-x`: exclusive, only this interface's servers are used.
    let mut child = Command::new("resolvconf")
        .args(["-a", INTERFACE, "-m", "0", "-x"])
        .stdin(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("running resolvconf")?;
    let mut stdin = child.stdin.take().context("resolvconf stdin")?;
    stdin.write_all(resolv_conf_contents(servers, false).as_bytes()).await?;
    drop(stdin);
    let output = child.wait_with_output().await?;
    if !output.status.success() {
        bail!("resolvconf -a {INTERFACE} failed: {}", String::from_utf8_lossy(&output.stderr).trim());
    }
    Ok(())
}

/// File backend: backs up `resolv_conf` into `backup_dir` (per the module contract) and writes `servers`.
/// A leftover backup from a crashed run is restored first, so the backup always holds the original.
pub fn apply_file(resolv_conf: &Path, backup_dir: &Path, servers: &[IpAddr]) -> Result<()> {
    restore_file(resolv_conf, backup_dir)?;
    std::fs::create_dir_all(backup_dir).with_context(|| format!("creating {}", backup_dir.display()))?;

    let meta = std::fs::symlink_metadata(resolv_conf);
    match meta {
        Ok(meta) if meta.file_type().is_symlink() => {
            let target = std::fs::read_link(resolv_conf)?;
            config::write_atomic(&backup_dir.join(SYMLINK_BACKUP_FILE), target.as_os_str().as_encoded_bytes(), 0o600)?;
            // Replace the link itself; writing through it would change a file someone else manages.
            std::fs::remove_file(resolv_conf).with_context(|| format!("removing symlink {}", resolv_conf.display()))?;
        }
        Ok(_) => {
            let original = std::fs::read(resolv_conf).with_context(|| format!("reading {}", resolv_conf.display()))?;
            config::write_atomic(&backup_dir.join(BACKUP_FILE), &original, 0o600)?;
        }
        // No resolv.conf at all: restoring means removing ours, which an empty backup can't express; back up
        // an empty file so the restore leaves an empty (equivalent) resolv.conf.
        Err(e) if e.kind() == io::ErrorKind::NotFound => {
            config::write_atomic(&backup_dir.join(BACKUP_FILE), b"", 0o600)?;
        }
        Err(e) => return Err(e).with_context(|| format!("inspecting {}", resolv_conf.display())),
    }
    write_resolv_conf(resolv_conf, resolv_conf_contents(servers, true).as_bytes())
}

/// Writes resolv.conf atomically, or in place when it's a bind mount (where `rename` fails with EBUSY).
fn write_resolv_conf(path: &Path, contents: &[u8]) -> Result<()> {
    match config::write_atomic(path, contents, 0o644) {
        Ok(()) => Ok(()),
        Err(e) if e.raw_os_error() == Some(EBUSY) => {
            let mut file = std::fs::OpenOptions::new()
                .write(true)
                .truncate(true)
                .open(path)
                .with_context(|| format!("opening {}", path.display()))?;
            file.write_all(contents)?;
            file.sync_all()?;
            Ok(())
        }
        Err(e) => Err(e).with_context(|| format!("writing {}", path.display())),
    }
}

fn which(program: &str) -> bool {
    std::env::var_os("PATH")
        .map(|paths| std::env::split_paths(&paths).any(|dir| dir.join(program).is_file()))
        .unwrap_or(false)
}

/// Undoes DNS changes from any backend: the openresolv entry for [`INTERFACE`], then the file backend.
/// systemd-resolved settings are per-link and vanish with the link.
pub async fn recover() -> Result<Vec<String>> {
    let mut actions = recover_resolvconf().await?;
    actions.extend(restore_file(Path::new(RESOLV_CONF), Path::new(config::RUN_DIR))?);
    Ok(actions)
}

async fn recover_resolvconf() -> Result<Vec<String>> {
    // openresolv's `-l` prints the entry for the interface and fails when there is none. Other resolvconf
    // implementations don't have `-l`; the file-backend restore below covers those hosts.
    let listed = match Command::new("resolvconf").args(["-l", INTERFACE]).output().await {
        Ok(output) => output.status.success() && !output.stdout.is_empty(),
        Err(e) if e.kind() == io::ErrorKind::NotFound => false,
        Err(e) => return Err(e).context("running resolvconf"),
    };
    if !listed {
        return Ok(Vec::new());
    }
    let status = Command::new("resolvconf").args(["-d", INTERFACE]).status().await?;
    anyhow::ensure!(status.success(), "resolvconf -d {INTERFACE} failed ({status})");
    Ok(vec![format!("removed resolvconf entry for {INTERFACE}")])
}

/// Restores `resolv_conf` from the backups in `backup_dir`, per the module contract.
pub fn restore_file(resolv_conf: &Path, backup_dir: &Path) -> Result<Vec<String>> {
    let backup = backup_dir.join(BACKUP_FILE);
    let symlink_backup = backup_dir.join(SYMLINK_BACKUP_FILE);
    let link_target = read_optional(&symlink_backup)?.map(|t| PathBuf::from(String::from_utf8_lossy(&t).trim()));
    let contents = read_optional(&backup)?;
    if link_target.is_none() && contents.is_none() {
        return Ok(Vec::new());
    }

    let mut actions = Vec::new();
    if carries_marker(resolv_conf)? {
        if let Some(target) = link_target {
            let _ = std::fs::remove_file(resolv_conf);
            std::os::unix::fs::symlink(&target, resolv_conf)
                .with_context(|| format!("recreating symlink {} -> {}", resolv_conf.display(), target.display()))?;
            actions.push(format!("restored {} -> {}", resolv_conf.display(), target.display()));
        } else if let Some(contents) = contents {
            write_resolv_conf(resolv_conf, &contents)
                .with_context(|| format!("restoring {}", resolv_conf.display()))?;
            actions.push(format!("restored {} from backup", resolv_conf.display()));
        }
    } else {
        actions.push(format!("discarded stale DNS backup ({} was rewritten since)", resolv_conf.display()));
    }
    for file in [backup, symlink_backup] {
        match std::fs::remove_file(&file) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => {
                return Err(e).with_context(|| format!("removing {}", file.display()));
            }
            _ => {}
        }
    }
    Ok(actions)
}

fn carries_marker(path: &Path) -> Result<bool> {
    // symlink_metadata: a symlink at this path was never written by us.
    match std::fs::symlink_metadata(path) {
        Ok(meta) if meta.file_type().is_file() => {
            let text = std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
            Ok(text.lines().next() == Some(MARKER))
        }
        Ok(_) => Ok(false),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(e).with_context(|| format!("inspecting {}", path.display())),
    }
}

fn read_optional(path: &Path) -> Result<Option<Vec<u8>>> {
    match std::fs::read(path) {
        Ok(bytes) => Ok(Some(bytes)),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    const OURS: &str = "# Generated by protontui\nnameserver 10.2.0.1\n";
    const ORIGINAL: &[u8] = b"# from DHCP\nnameserver 192.168.1.1\nsearch lan\n";

    #[test]
    fn nothing_to_do_without_backup() {
        let dir = tempfile::tempdir().unwrap();
        let resolv = dir.path().join("resolv.conf");
        fs::write(&resolv, ORIGINAL).unwrap();
        assert!(restore_file(&resolv, dir.path()).unwrap().is_empty());
        assert_eq!(fs::read(&resolv).unwrap(), ORIGINAL);
    }

    #[test]
    fn restores_regular_file_byte_for_byte() {
        let dir = tempfile::tempdir().unwrap();
        let resolv = dir.path().join("resolv.conf");
        fs::write(&resolv, OURS).unwrap();
        fs::write(dir.path().join(BACKUP_FILE), ORIGINAL).unwrap();

        assert_eq!(restore_file(&resolv, dir.path()).unwrap().len(), 1);
        assert_eq!(fs::read(&resolv).unwrap(), ORIGINAL);
        assert!(!dir.path().join(BACKUP_FILE).exists());
        // Second run: no-op.
        assert!(restore_file(&resolv, dir.path()).unwrap().is_empty());
    }

    #[test]
    fn restores_symlink() {
        let dir = tempfile::tempdir().unwrap();
        let resolv = dir.path().join("resolv.conf");
        let target = dir.path().join("stub-resolv.conf");
        fs::write(&target, ORIGINAL).unwrap();
        fs::write(&resolv, OURS).unwrap();
        fs::write(dir.path().join(SYMLINK_BACKUP_FILE), target.to_str().unwrap()).unwrap();

        restore_file(&resolv, dir.path()).unwrap();
        assert_eq!(fs::read_link(&resolv).unwrap(), target);
        assert!(!dir.path().join(SYMLINK_BACKUP_FILE).exists());
    }

    #[test]
    fn apply_then_restore_is_byte_for_byte() {
        let dir = tempfile::tempdir().unwrap();
        let resolv = dir.path().join("resolv.conf");
        let backups = dir.path().join("run");
        fs::write(&resolv, ORIGINAL).unwrap();
        let servers: Vec<IpAddr> = vec!["10.2.0.1".parse().unwrap()];

        apply_file(&resolv, &backups, &servers).unwrap();
        let ours = fs::read_to_string(&resolv).unwrap();
        assert!(ours.starts_with(MARKER));
        assert!(ours.ends_with("nameserver 10.2.0.1\n"));
        // Applying again (reconnect, or after a crash) must not back up our own file.
        apply_file(&resolv, &backups, &["9.9.9.9".parse().unwrap()]).unwrap();

        restore_file(&resolv, &backups).unwrap();
        assert_eq!(fs::read(&resolv).unwrap(), ORIGINAL);
    }

    #[test]
    fn apply_replaces_a_symlink_and_restores_it() {
        let dir = tempfile::tempdir().unwrap();
        let resolv = dir.path().join("resolv.conf");
        let target = dir.path().join("stub-resolv.conf");
        fs::write(&target, ORIGINAL).unwrap();
        std::os::unix::fs::symlink(&target, &resolv).unwrap();

        apply_file(&resolv, &dir.path().join("run"), &["10.2.0.1".parse().unwrap()]).unwrap();
        assert!(fs::symlink_metadata(&resolv).unwrap().file_type().is_file());
        assert_eq!(fs::read(&target).unwrap(), ORIGINAL, "the link target must stay untouched");

        restore_file(&resolv, &dir.path().join("run")).unwrap();
        assert_eq!(fs::read_link(&resolv).unwrap(), target);
    }

    #[test]
    fn stale_backup_is_discarded_without_touching_the_file() {
        let dir = tempfile::tempdir().unwrap();
        let resolv = dir.path().join("resolv.conf");
        let rewritten = b"nameserver 1.1.1.1\n";
        fs::write(&resolv, rewritten).unwrap();
        fs::write(dir.path().join(BACKUP_FILE), ORIGINAL).unwrap();

        restore_file(&resolv, dir.path()).unwrap();
        assert_eq!(fs::read(&resolv).unwrap(), rewritten);
        assert!(!dir.path().join(BACKUP_FILE).exists());
    }
}
